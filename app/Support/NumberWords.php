namespace App\Support;

/**
 * Слова для номеров сертификатов: три латинские буквы, казахские слова о природе (латиница 2021: Q, J).
 * Слова подобраны так, чтобы их не путали на слух по телефону: любые два слова различаются минимум двумя буквами
 * (Q≈K, J≈Y, Z≈S считаются одной буквой). Новое слово проверяет тест; исключения (слова, оставленные по решению владельца) перечислены в тесте. Список только дополняется в конец (до 100 слов).
 * Чем больше слов, тем больше вариантов номера: N слов дают N·(N−1) пар, умноженных на 10 000 цифр.
 */
final class NumberWords
{
    public const LIST = [
        'TAU', 'NUR', 'GUL', 'ARU', 'KOL', 'JEL', 'KUN', 'QAR', 'ALA', 'QYS', 'MUZ', 'BAL', 'SAY', 'TAL',
        'JAZ', 'KUZ', // времена года вместе с QYS: лето, осень, зима
    ];
}
